import csv

def run_tests(path: str = "/content/tests.csv") -> None:
    """
    Test ReCraft AI using customer questions and expected keywords.
    Display the pass rate.
    """
    with open(path, "r", encoding="utf-8") as file:
        rows = list(csv.DictReader(file))

    passed = 0

    for row in rows:
        answer = chain.invoke({
            "history": [],
            "question": row["question"]
        })

        expected = row["must_include"].lower()
        success = expected in answer.lower()

        if success:
            passed += 1

        print(
            "PASS" if success else "FAIL",
            "|",
            row["question"],
            "| Expected:",
            expected
        )
        print("Answer:", answer)
        print("-" * 60)

    total = len(rows)
    percentage = (passed / total) * 100 if total else 0

    print(f"\nTest Results: {passed}/{total}")
    print(f"Pass Percentage: {percentage:.2f}%")


run_tests()

