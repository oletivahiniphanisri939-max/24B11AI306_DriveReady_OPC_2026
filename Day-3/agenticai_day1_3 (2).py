def get_reuse_ideas(waste_material: str) -> list[str]:
    """
    Return reuse ideas for a given waste material.
    """
    ideas = {
        "plastic bottles": [
            "Make a small planter",
            "Create a bird feeder",
            "Use as a storage container"
        ],
        "newspapers": [
            "Make paper crafts",
            "Create paper bags",
            "Use for gift wrapping"
        ],
        "vegetable peels": [
            "Make compost",
            "Use in a suitable compost bin"
        ],
        "old clothes": [
            "Make cleaning cloths",
            "Create reusable cloth bags"
        ],
        "glass jars": [
            "Use as storage containers",
            "Make decorative containers"
        ],
        "cardboard boxes": [
            "Make storage organisers",
            "Create craft projects"
        ]
    }

    material = waste_material.lower().strip()

    return ideas.get(
        material,
        ["Please check local recycling options for this material."]
    )


def is_safe_for_diy(waste_material: str) -> bool:
    """
    Check whether a material is suitable for ordinary DIY reuse.
    """
    unsafe_materials = {
        "electronic waste",
        "batteries",
        "chemicals",
        "medical waste",
        "paint containers"
    }

    material = waste_material.lower().strip()

    return material not in unsafe_materials


